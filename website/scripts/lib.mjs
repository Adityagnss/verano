// Shared helpers for the generators: where the repo is, how to turn a link in a source document into a link that works on
// the site, and how to write a generated page. Public docs only: the PRIVATE list is never published, and links to it are
// turned into plain text.
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

export const WEBSITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
export const ROOT = path.resolve(WEBSITE, "..")
export const REPO_URL = "https://github.com/Adityagnss/verano"
export const BRANCH = "main"

/** Source file (repo-relative) -> route on the site. One source of truth: the page is generated from the file. */
export const ROUTES = {
  "README.md": "/",
  "docs/guides/improve-a-prompt.md": "/guides/improve-a-prompt",
  "docs/guides/add-a-provider.md": "/guides/add-a-provider",
  "docs/guides/add-a-scanner-language.md": "/guides/add-a-scanner-language",
  "docs/guides/self-hosting.md": "/self-hosting/",
  "cli/README.md": "/reference/cli",
  ".github/actions/verano-run/README.md": "/reference/github-action",
  "docs/integrations/README.md": "/reference/integrations",
  "docs/integrations/registry.yaml": "/reference/integrations",
  "examples/README.md": "/reference/examples",
}

/** Never published, and never linked: links to these keep their text only. */
const PRIVATE = [
  /^docs\/adr(\/|$)/,
  /^docs\/checkpoints(\/|$)/,
  /^docs\/(BACKLOG|PENDING_CHECKS|ACCEPTANCE|DEVELOPMENT|ENGINEERING_STANDARDS|REFERENCES)\.md$/,
  /^docs\/(benchmarks|resilience)\.md$/,
  /^docs\/architecture\.md$/,
]
export const isPrivate = (repoPath) => PRIVATE.some((re) => re.test(repoPath))

/** Rewrite the relative links of a Markdown document that lives at `srcRel` (repo-relative). */
export function rewriteLinks(markdown, srcRel) {
  const srcDir = path.posix.dirname(srcRel)
  let inFence = false
  return markdown
    .split("\n")
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) inFence = !inFence
      if (inFence) return line
      return line.replace(/\[([^\]]*)\]\(([^)\s]+)\)/g, (whole, text, href) => {
        if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(href)) return whole
        const [target, hash = ""] = href.split("#")
        const repoPath = path.posix.normalize(path.posix.join(srcDir, target)).replace(/\/$/, "")
        if (isPrivate(repoPath)) return text
        const anchor = hash ? `#${hash}` : ""
        if (ROUTES[repoPath]) return `[${text}](${ROUTES[repoPath]}${ROUTES[repoPath] === "/" ? "" : anchor})`
        const abs = path.join(ROOT, repoPath)
        if (!fs.existsSync(abs)) return text
        const kind = fs.statSync(abs).isDirectory() ? "tree" : "blob"
        return `[${text}](${REPO_URL}/${kind}/${BRANCH}/${repoPath}${anchor})`
      })
    })
    .join("\n")
}

/** The date of the last commit that touched a source file (so "last updated" points at the real source). */
export function lastCommitDate(repoPath) {
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%cI", "--", repoPath], { cwd: ROOT }).toString().trim()
    return out || null
  } catch {
    return null
  }
}

/** Write a generated page with the front matter the theme uses (edit link and last-updated point at the source). */
export function writePage(outRel, body, { editPath, sources = [editPath], title } = {}) {
  const dates = sources.map((s) => lastCommitDate(s)).filter(Boolean).sort()
  const fm = ["---"]
  if (title) fm.push(`title: ${JSON.stringify(title)}`)
  if (editPath) fm.push(`editPath: ${editPath}`)
  if (dates.length) fm.push(`lastUpdated: ${dates[dates.length - 1]}`)
  fm.push("---", "", "<!-- Generated by website/scripts. Do not edit: change the source file instead. -->", "")
  const out = path.join(WEBSITE, outRel)
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, fm.join("\n") + body.trimEnd() + "\n")
}

export const read = (repoPath) => fs.readFileSync(path.join(ROOT, repoPath), "utf8")

/** Make text safe in a Markdown table cell (no pipes, tags or Vue interpolation). */
export const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n+/g, " ")
    .replace(/</g, "&lt;")
    .replace(/\{\{/g, "&#123;&#123;")
